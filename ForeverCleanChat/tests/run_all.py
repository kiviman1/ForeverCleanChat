#!/usr/bin/env python3
"""Execute the addon itself in Lua 5.1 and 5.3; Python supplies no classifier oracle.

Requires the installed `lupa` package with lua51 and lua53 backends.
Run from any directory: python tests/run_all.py
Reports are written to tests/results/latest.json and tests/results/latest.md.
"""
