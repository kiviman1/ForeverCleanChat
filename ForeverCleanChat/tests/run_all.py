def plain(value):
    if hasattr(value, "items"):
        items = dict(value.items())
        if items and set(items) == set(range(1, len(items) + 1)):
            return [plain(items[i]) for i in range(1, len(items) + 1)]
        return {str(key): plain(item) for key, item in items.items()}
    return value


def compile_checks():
    spec = importlib.util.spec_from_file_location("fcc_build_rule_data", ROOT / "tools/build_rule_data.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    first = module.outputs(module.read_source())
    second = module.outputs(module.read_source())
    if first != second:
        raise AssertionError("same source produced different generated bytes")
    paths = [ROOT / "Data.generated.lua", ROOT / "tests/Fixtures.generated.lua"]
    for path, content in zip(paths, first):
        if path.read_bytes() != content:
            raise AssertionError(f"stale generated artifact: {path.name}; run tools/build_rule_data.py")
    hashes = {path.relative_to(ROOT).as_posix(): hashlib.sha256(content).hexdigest() for path, content in zip(paths, first)}
    unit_path = ROOT / "tools/test_build_rule_data.py"
    unit_result = None
    if unit_path.exists():
        command = subprocess.run([sys.executable, str(unit_path)], capture_output=True, text=True, encoding="utf-8")
        match = re.search(r"Ran (\d+) tests?", command.stdout + command.stderr)
        unit_result = {"exit_code": command.returncode, "tests_run": int(match.group(1)) if match else None,
                       "stdout": command.stdout, "stderr": command.stderr}
        if command.returncode:
            raise AssertionError("compiler unit tests failed:\n" + command.stdout + command.stderr)
    return {"status": "passed", "separate_compilations": 2, "hashes": hashes, "compiler_unit_tests": unit_result}


def run_lua(engine, suites):
    module = importlib.import_module("lupa." + engine)
    lua = module.LuaRuntime(unpack_returned_tuples=True)
    lua.globals().arg = lua.table_from({1: ROOT.as_posix()})
    log = []

    def capture(*values):
        line = "\t".join(str(value) for value in values)
        log.append(line)
        print(line)

    lua.globals().print = capture
    record = {"engine": module.__name__, "lua_version": ".".join(map(str, module.LUA_VERSION)), "suites": {}}
    for name, filename, key in (
        ("regression", "run.lua", "FCC_TEST_RESULT"),
        ("research", "run_research.lua", "FCC_RESEARCH_RESULT"),
        ("adversarial", "run_adversarial.lua", "FCC_ADVERSARIAL_RESULT"),
        ("ui", "run_ui.lua", "FCC_UI_RESULT"),
    ):
        if name not in suites:
            continue
        start = time.monotonic()
        error = None
        try:
            lua.execute((ROOT / "tests" / filename).read_text(encoding="utf-8"))
        except Exception as exc:
            error = str(exc)
        value = lua.globals()[key]
        result = plain(value) if value is not None else {"suite": name, "status": "failed_to_complete"}
        result["elapsed_seconds"] = round(time.monotonic() - start, 3)
        if error:
            result["execution_error"] = error
            print(f"{module.__name__} {name}: FAILED")
        record["suites"][name] = result
    record["output"] = log
    return record


def resolve_contracts(report):
    for runtime in report["runtimes"]:
        results = runtime["suites"]
        research = results.get("research")
        if not research:
            continue
        for contract in research.get("contracts", []):
            if contract["id"] == "contract_compile_deterministic":
                contract["status"] = "passed_offline" if report["compiler"]["status"] == "passed" else "failed"
                contract["evidence"] = "Two independent Python compilation calls produced identical Lua artifact bytes."
            elif contract["id"] == "contract_test_parity":
                classifier = research.get("classification", {})
                passed = classifier.get("failed") == 0 and classifier.get("total") == 1190
                contract["status"] = "passed_lua" if passed else "failed"
                contract["evidence"] = "All 595 original classification cases ran in balanced and strict on this real Lua runtime."
            elif contract["id"] == "contract_regression_existing":
                regression = results.get("regression")
                contract["status"] = "passed_lua" if regression and regression.get("failed") == 0 and not regression.get("execution_error") else "not_run" if not regression else "failed"
                contract["evidence"] = "Regression results are separately recorded; changed expectations are documented in tests/README.md."
            elif contract["id"] == "contract_no_bubbles_claim":
                contract["status"] = "documented_scope_limit"
                contract["evidence"] = "Only registered chat-frame filter events are mocked; no bubbles/mailbox/group-finder support is claimed."
            elif contract["id"] == "contract_live_scope":
                contract["status"] = "pending_live_client"
                contract["evidence"] = "No access to an active target Forever client; real API support, callback layout and scope are unverified."


def success(report):
    if report["compiler"]["status"] != "passed":
        return False
    for runtime in report["runtimes"]:
        for suite in runtime["suites"].values():
            if suite.get("execution_error") or suite.get("status") == "failed_to_complete" or suite.get("failed", 0):
                return False
            if any(c.get("status") in {"failed", "not_implemented"} for c in suite.get("contracts", [])):
                return False
            if any(c.get("status") in {"failed", "not_implemented"} for c in suite.get("checks", [])):
                return False
            if suite.get("extra", {}).get("status") in {"failed", "not_implemented"}:
                return False
            for group in ("classification", "adapter"):
                if suite.get(group, {}).get("failed", 0):
                    return False
    return True


def markdown(report):
    lines = ["# ForeverCleanChat executed test report", "", f"Generated UTC: {report['executed_at_utc']}", "",
             f"Python: `{report['python_executable']}` ({report['python_version']})", "",
             "The original unmodified v0.1.0 suite was actually run before this change: **194/194 on Lua 5.1 and 194/194 on Lua 5.3**. The adapted regression and new research checks are reported separately below.", "",
             "| Runtime | Adapted v0.1.0 regression | JSON classifier/profile checks | Mock adapter/profile checks |", "|---|---:|---:|---:|"]
    for runtime in report["runtimes"]:
        suites = runtime["suites"]
        reg = suites.get("regression", {})
        research = suites.get("research", {})
        classifier = research.get("classification", {})
        adapter = research.get("adapter", {})
        fraction = lambda value: f"{value.get('passed', 0)}/{value.get('total', 0)}"
        lines.append(f"| {runtime['engine']} / Lua {runtime['lua_version']} | {fraction(reg)} | {fraction(classifier)} | {fraction(adapter)} |")
    lines += ["", "595 JSON classification cases each run in two profiles: 1190 classifier evaluations per runtime, plus 1190 callback evaluations. Fixtures are specifications, not previous pass results.", "", "## Engineering acceptance contracts", "", "| Contract | Lua 5.1 | Lua 5.3 |", "|---|---|---|"]
    contracts = {}
    for runtime in report["runtimes"]:
        for row in runtime["suites"].get("research", {}).get("contracts", []):
            contracts.setdefault(row["id"], {})[runtime["lua_version"]] = row["status"]
    for key, states in contracts.items():
        lines.append(f"| {key} | {states.get('5.1', 'not_run')} | {states.get('5.3', 'not_run')} |")
    lines += ["", "`passed_mock` verifies only the isolated mock contract. `pending_live_client` and `documented_scope_limit` are not runtime compatibility passes.", "", "## Compiler", "", f"Status: {report['compiler']['status']}", ""]
    for path, digest in report["compiler"].get("hashes", {}).items():
        lines.append(f"- `{path}`: `{digest}`")
    units = report["compiler"].get("compiler_unit_tests")
    if units:
        lines += ["", f"Compiler validation unit tests: {units.get('tests_run', 'unknown count')} actually executed; exit code {units['exit_code']}."]
    lines += ["", "Two compilations must produce identical bytes and match committed generated files. Python does not normalize or classify fixture text; classification is the actual addon Lua implementation.", "", "## Intentional regression expectation changes", ""]
    lines += ["- " + line for line in REGRESSION_CHANGES]
    lines += ["", "## Independent adversarial regressions", "", "These contract-derived audit cases are separate from the original 595 JSON fixtures. Source fixture expectations remain unchanged.", "",
              "| Runtime | Cases | Classifier/profile checks | Mock callback/profile checks | Engineering assertions |", "|---|---:|---:|---:|---:|"]
    for runtime in report["runtimes"]:
        adversarial=runtime["suites"].get("adversarial",{})
        lines.append(f"| Lua {runtime['lua_version']} | {adversarial.get('case_count', 0)} | {fraction(adversarial.get('classification', {}))} | {fraction(adversarial.get('adapter', {}))} | {adversarial.get('engineering_assertions', 0)} |")
    lines += ["", "| Adversarial engineering group | Lua 5.1 | Lua 5.3 |", "|---|---|---|"]
    extra_checks={}
    for runtime in report["runtimes"]:
        for row in runtime["suites"].get("adversarial",{}).get("checks",[]):
            extra_checks.setdefault(row["id"],{})[runtime["lua_version"]]=row["status"]
    for key,states in extra_checks.items():
        lines.append(f"| {key} | {states.get('5.1', 'not_run')} | {states.get('5.3', 'not_run')} |")
    lines += ["", "## Control panel and minimap interactions", "",
              "These checks execute the actual addon callbacks on stateful native-frame doubles. No browser drawing or live WoW screenshot is used as evidence of UI compatibility.", "",
              "| Runtime | Interaction assertions | Native UI rendering | Target Forever client |", "|---|---:|---|---|"]
    for runtime in report["runtimes"]:
        ui = runtime["suites"].get("ui", {})
        lines.append(f"| Lua {runtime['lua_version']} | {fraction(ui)} | {ui.get('native_rendering', 'not_run')} | {ui.get('target_client', 'not_run')} |")
    ui_groups = {}
    for runtime in report["runtimes"]:
        for row in runtime["suites"].get("ui", {}).get("checks", []):
            ui_groups.setdefault(row["id"], {})[runtime["lua_version"]] = row["status"]
    lines += ["", "| UI interaction group | Lua 5.1 | Lua 5.3 |", "|---|---|---|"]
    for key, states in ui_groups.items():
        lines.append(f"| {key} | {states.get('5.1', 'not_run')} | {states.get('5.3', 'not_run')} |")
    failures = []
    for runtime in report["runtimes"]:
        for name, result in runtime["suites"].items():
            if result.get("execution_error"):
                failures.append(f"- {runtime['engine']} {name}: `{result['execution_error'].splitlines()[0]}`")
    lines += ["", "## Failures", ""] + (failures or ["None in executed local checks."])
    lines += ["", "Live Forever integration was **not run**. No spam was sent to a real chat channel. Actual event support, target vararg positions, secret-value behavior and third-party chat panels still require local target-client validation.", ""]
    return "\n".join(lines)


def main():
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--suite", choices=["all", "regression", "research", "adversarial", "ui"], default="all")
    parser.add_argument("--report", type=Path, default=ROOT / "tests/results/latest.json")
    args = parser.parse_args()
    suites = {"regression", "research", "adversarial", "ui"} if args.suite == "all" else {args.suite}
    report = {"executed_at_utc": datetime.now(timezone.utc).isoformat(), "python_executable": sys.executable,
              "python_version": sys.version.split()[0], "original_baseline": {"lua51": {"passed":194,"total":194},"lua53":{"passed":194,"total":194}},
              "regression_expectation_changes":REGRESSION_CHANGES, "runtimes":[]}
    try:
        report["compiler"] = compile_checks()
    except Exception as exc:
        report["compiler"] = {"status":"failed", "error":str(exc)}
        print("Compiler: " + str(exc))
    for engine in ("lua51", "lua53"):
        print("=== " + engine + " ===")
        try:
            report["runtimes"].append(run_lua(engine, suites))
        except Exception as exc:
            report["runtimes"].append({"engine":"lupa."+engine,"lua_version":"5.1" if engine=="lua51" else "5.3",
                                       "suites":{"runtime":{"status":"failed_to_complete","execution_error":str(exc)}}})
            print(str(exc))
    resolve_contracts(report)
    report["local_checks_passed"] = success(report)
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    args.report.with_suffix(".md").write_text(markdown(report),encoding="utf-8")
    print("Report: " + str(args.report))
    return 0 if report["local_checks_passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
